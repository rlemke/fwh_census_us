"""Give every published page a link back to the FFL that produced it.

Many renderers already end their page with a "Generated by Facetwork workflow …
· view FFL · source repo" footer (``attribution.footer_html`` and the copies in
each domain's ``_lib``), but about a third of the published site came from
renderers that never did — tiled road maps, the grid, health, cancer tables,
the reproduction studies. Retrofitting a dozen renderers in a dozen repos only
helps pages that are rebuilt, and several of these are expensive to rebuild.

So the publisher does it: :func:`stamp_tree` walks the site checkout on every
publish and adds the footer to any map page that does not already carry one,
looking up its producer in :data:`REGISTRY`. That converges the WHOLE site, not
just the bundles in the current call, and a rebuilt page that comes back
without a footer is stamped again on its way out.

⚠️ A page whose producer is not in the registry is left untouched and REPORTED,
never guessed — a link to the wrong workflow is worse than no link.
⚠️ Gallery index pages (the root and each ``<section>/index.html``) are written
by the publisher itself and are never stamped.
⚠️ The injected footer carries no "generated <time>": the publisher does not
know when the page was rendered, and the publish time is not that.
"""

