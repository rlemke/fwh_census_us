# The publisher's own landing pages carry this rule from ``publish._HTML_HEAD``.
_GALLERY_SIGNATURE = "h2 a{color:#222"


def _is_gallery_index(rel: str, html: str) -> bool:
    """The root or a section ``index.html`` that the publisher generated.

    Checked by content, not depth alone: a single-segment dest such as ``amr``
    puts a MAP at ``amr/index.html``, exactly where a section index would be."""
    return rel.count("/") <= 1 and rel.endswith("index.html") and _GALLERY_SIGNATURE in html


def _is_redirect(html: str) -> bool:
    """A stub left at a moved page's old path to forward its links; not a map."""
    return 'http-equiv="refresh"' in html.lower() and len(html) < 2000


def lookup(page_dir: str, registry: dict[str, tuple[str, str]] | None = None
           ) -> tuple[str, str] | None:
    """The producer of the page in ``page_dir`` (a site-relative directory), by
    longest matching path prefix on whole segments; None if unknown."""
    reg = REGISTRY if registry is None else registry
    parts = [p for p in page_dir.strip("/").split("/") if p]
    for n in range(len(parts), 0, -1):
        hit = reg.get("/".join(parts[:n]))
        if hit:
            return hit
    return None


def footer_html(workflow: str, ffl_url: str) -> str:
    """The same inline-styled footer the renderers emit, minus the timestamp."""
    repo_url = ffl_url.split("/blob/")[0] if "/blob/" in ffl_url else ffl_url
    link = 'target="_blank" rel="noopener" style="color:#1565c0;text-decoration:none"'
    return (
        '<div data-fw-provenance="1" style="position:fixed;bottom:10px;left:10px;'
        "z-index:9999;background:rgba(255,255,255,0.92);border-radius:6px;padding:6px 10px;"
        "box-shadow:0 1px 4px rgba(0,0,0,0.2);font:11px system-ui,sans-serif;"
        'color:#444;max-width:440px">'
        "Generated by Facetwork workflow "
        f'<code style="background:#f0f0f0;padding:0 3px;border-radius:3px">{escape(workflow)}</code>'
        f' &middot; <a href="{escape(ffl_url)}" {link}>view FFL</a>'
        f' &middot; <a href="{escape(repo_url)}" {link}>source repo</a></div>'
    )


def inject(html: str, workflow: str, ffl_url: str) -> str | None:
    """``html`` with the footer added before ``</body>``; None if it already has one.

    Several renderers omit ``</body>`` (and ``</html>``) — legal HTML, the
    parser closes them — so the footer then goes before ``</html>``, or at the
    very end."""
    if _MARKER in html:
        return None
    low = html.lower()
    i = low.rfind("</body>")
    if i < 0:
        i = low.rfind("</html>")
    if i < 0:
        return html.rstrip() + "\n" + footer_html(workflow, ffl_url) + "\n"
    return html[:i] + footer_html(workflow, ffl_url) + "\n" + html[i:]


def stamp_tree(repo_dir: str, registry: dict[str, tuple[str, str]] | None = None
               ) -> tuple[list[str], list[str]]:
    """Stamp every unattributed map page under ``repo_dir`` in place.

    Returns ``(stamped, unknown)`` site-relative paths: pages given a footer,
    and pages lacking one whose producer is not registered."""
    stamped: list[str] = []
    unknown: list[str] = []
    for dirpath, dirs, files in os.walk(repo_dir):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        rel_dir = os.path.relpath(dirpath, repo_dir)
        rel_dir = "" if rel_dir == "." else rel_dir.replace(os.sep, "/")
        for fn in sorted(files):
            if not fn.lower().endswith(".html"):
                continue
            rel = f"{rel_dir}/{fn}" if rel_dir else fn
            path = os.path.join(dirpath, fn)
            with open(path, encoding="utf-8", errors="surrogateescape") as f:
                html = f.read()
            if _MARKER in html or _is_gallery_index(rel, html) or _is_redirect(html):
                continue
            hit = lookup(rel_dir, registry)
            if not hit:
                unknown.append(rel)
                continue
            out = inject(html, *hit)
            with open(path, "w", encoding="utf-8", errors="surrogateescape") as f:
                f.write(out)
            stamped.append(rel)
    return stamped, unknown
